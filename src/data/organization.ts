// Helper auto-suggest English prefix from Thai prefix
export function suggestEnglishPrefix(thaiPrefix: string): string {
  switch (thaiPrefix) {
    case 'นาย':
      return 'Mr.';
    case 'นาง':
      return 'Mrs.';
    case 'นางสาว':
      return 'Miss';
    case 'ดร.':
      return 'Dr.';
    case 'ว่าที่ ร.ต.':
    case 'ว่าที่ ร.ต. หญิง':
      return 'Acting Sub. Lt.';
    default:
      return 'Mr.';
  }
}

